import matplotlib.pyplot as plt
days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri']
scores = ['70', '85', '60', '90', '75']
plt.plot(days, scores)
plt.show()
plt.plot(days, scores)
plt.title('My Quiz Score Tracker')
plt.xlabel('Day of the week')
plt.ylabel('Quiz Scores')
plt.grid(true)
plt.ylim(0, 100)
plt.show()
plt.plot(days, scores, color='blue', marker='o', linestyle='dashed', linewdith=2)
plt.title('My Quiz Score Tracker')
plt.xlabel('Day of the week')
plt.ylabel('Quiz Scores')
plt.grid(true)
plt.ylim(0, 100)
plt.show()
plt.bar(days, scores, color='orange')
plt.xlabel('Day of the week')
plt.ylabel('Quiz Scores')
plt.grid(true)
plt.ylim(0, 100)
plt.show()